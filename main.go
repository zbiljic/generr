var (
	typeNames  = flag.String("type", "", "comma-separated list of type names; must be set")
	output     = flag.String("output", "", "output file name; default srcdir/<type>_generr.go")
	trimprefix = flag.String("trimprefix", "", "trim the `prefix` from the package path used in operation names")
	buildTags  = flag.String("tags", "", "comma-separated list of build tags to apply")
	exported   = flag.Bool("exported", false, "generate error functions only for exported methods")
)

// Usage is a replacement usage function for the flags package.
func Usage() {
	fmt.Fprintf(os.Stderr, "Usage of generr:\n")
	fmt.Fprintf(os.Stderr, "\tgenerr [flags] -type T [directory]\n")
	fmt.Fprintf(os.Stderr, "\tgenerr [flags] -type T files... # Must be a single package\n")
	fmt.Fprintf(os.Stderr, "Flags:\n")
	flag.PrintDefaults()
}

func main() {
	log.SetFlags(0)
	log.SetPrefix("generr: ")
	flag.Usage = Usage
	flag.Parse()
	if len(*typeNames) == 0 {
		flag.Usage()
		os.Exit(2)
	}
	names := strings.Split(*typeNames, ",")
	var tags []string
	if len(*buildTags) > 0 {
		tags = strings.Split(*buildTags, ",")
	}

	// We accept either one directory or a list of files. Which do we have?
	args := flag.Args()
	if len(args) == 0 {
		// Default: process whole package in current directory.
		args = []string{"."}
	}

	// Parse the package once.
	var dir string
	g := Generator{
		trimPrefix:   *trimprefix,
		exportedOnly: *exported,
	}
	if len(args) == 1 && isDirectory(args[0]) {
		dir = args[0]
	} else {
		if len(tags) != 0 {
			log.Fatal("-tags option applies only to directories, not when files are specified")
		}
		dir = filepath.Dir(args[0])
	}

	if err := g.parsePackage(args, tags); err != nil {
		log.Fatal(err)
	}

	// Nothing is written unless the whole file could be generated.
	src, err := g.run(names)
	if err != nil {
		log.Fatal(err)
	}

	// Write to file.
	outputName := *output
	if outputName == "" {
		baseName := fmt.Sprintf("%s_generr.go", names[0])
		outputName = filepath.Join(dir, strings.ToLower(baseName))
	}
	err = os.WriteFile(outputName, src, 0o644)
	if err != nil {
		log.Fatalf("writing output: %s", err)
	}
}

// run generates the error functions for the named types and returns the
// formatted source of the output file.
func (g *Generator) run(typeNames []string) ([]byte, error) {
	g.buf.Reset()
	g.imports = map[string]fileImport{"fmt": {path: "fmt"}} // Used by all methods.

	// Run generate for each type.
	for _, typeName := range typeNames {
		if err := g.generate(typeName); err != nil {
			return nil, err
		}
	}

	// The imports are only known once all functions are generated, so the
	// header and package clause are put together last.
	var src bytes.Buffer
	fmt.Fprintf(&src, "// Code generated by \"generr\"; DO NOT EDIT.\n")
	fmt.Fprintf(&src, "\n")
	fmt.Fprintf(&src, "package %s\n", g.pkg.name)
	g.writeImports(&src)
	src.Write(g.buf.Bytes())

	// Format the output.
	return formatSource(src.Bytes())
}

// isDirectory reports whether the named file is a directory.
func isDirectory(name string) bool {
	info, err := os.Stat(name)
	if err != nil {
		log.Fatal(err)
	}
	return info.IsDir()
}

// Generator holds the state of the analysis. Primarily used to buffer
// the output for format.Source.
type Generator struct {
	buf bytes.Buffer // Accumulated output: the generated functions.
	pkg *Package     // Package we are scanning.

	// Imports of the generated file, by the name the code refers to them.
	imports map[string]fileImport

	trimPrefix   string
	exportedOnly bool

	logf func(format string, args ...interface{}) // test logging hook; nil when not testing
}

func (g *Generator) Printf(format string, args ...interface{}) {
	fmt.Fprintf(&g.buf, format, args...)
}

// File holds a single parsed file and associated data.
type File struct {
	pkg  *Package  // Package to which this file belongs.
	file *ast.File // Parsed AST.
}

type Package struct {
	name      string
	info      *types.Info
	namespace string
	files     []*File
}

// fileImport is an import declaration of a source file.
type fileImport struct {
	alias string // Name given to the import in the source; empty when it has none.
	path  string
}

func (i fileImport) String() string {
	if i.alias != "" {
		return i.alias + " " + strconv.Quote(i.path)
	}
	return strconv.Quote(i.path)
}

func pkgLoadMode() packages.LoadMode {
	mode := packages.NeedName | packages.NeedTypes | packages.NeedTypesInfo | packages.NeedSyntax
	mode |= packages.NeedModule
	return mode
}

// parsePackage analyzes the single package constructed from the patterns and tags.
func (g *Generator) parsePackage(patterns, tags []string) error {
	cfg := &packages.Config{
		Mode:       pkgLoadMode(),
		Tests:      false,
		BuildFlags: []string{fmt.Sprintf("-tags=%s", strings.Join(tags, " "))},
		Logf:       g.logf,
	}
	pkgs, err := packages.Load(cfg, patterns...)
	if err != nil {
		return err
	}
	if len(pkgs) != 1 {
		return fmt.Errorf("error: %d packages matching %v", len(pkgs), strings.Join(patterns, " "))
	}
	g.addPackage(pkgs[0])
	return nil
}

// addPackage adds a type checked Package and its syntax files to the generator.
func (g *Generator) addPackage(pkg *packages.Package) {
	pkgPath, modPath := pkg.PkgPath, ""
	switch {
	case pkg.Module != nil:
		modPath = pkg.Module.Path
	case len(pkg.Syntax) > 0:
		// Files named on the command line are loaded as a synthetic package
		// that has no import path. Look up the package of their directory, so
		// that the namespace is the same as when the directory is given.
		dir := filepath.Dir(pkg.Fset.Position(pkg.Syntax[0].Package).Filename)
		if p, m, ok := g.locate(dir); ok {
			pkgPath, modPath = p, m
		}
	}

	g.pkg = &Package{
		name:      pkg.Name,
		info:      pkg.TypesInfo,
		namespace: namespace(pkgPath, pkg.Name, modPath, g.trimPrefix),
		files:     make([]*File, len(pkg.Syntax)),
	}

	for i, file := range pkg.Syntax {
		g.pkg.files[i] = &File{
			file: file,
			pkg:  g.pkg,
		}
	}
}

// locate returns the import path of the package in dir, and the path of the
// module it belongs to.
func (g *Generator) locate(dir string) (pkgPath, modPath string, ok bool) {
	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedModule,
		Dir:  dir,
		Logf: g.logf,
	}
	pkgs, err := packages.Load(cfg, ".")
	if err != nil || len(pkgs) != 1 || pkgs[0].Module == nil {
		return "", "", false
	}
	return pkgs[0].PkgPath, pkgs[0].Module.Path, true
}

// namespace returns the prefix of the operation names of a package: its
// import path relative to the module root, without trimPrefix. It falls back
// to the package name when that leaves nothing, as for the package at the
// module root, or when the module is not known.
func namespace(pkgPath, pkgName, modPath, trimPrefix string) string {
	if modPath == "" {
		return pkgName
	}

	ns := ""
	if pkgPath != modPath {
		rel, ok := strings.CutPrefix(pkgPath, modPath+"/")
		if !ok {
			return pkgName
		}
		ns = rel
	}

	if trimPrefix != "" {
		ns = strings.TrimPrefix(ns, trimPrefix)
		ns = strings.TrimPrefix(ns, "/")
	}
	if ns == "" {
		return pkgName
	}

	return ns
}

// generate produces the error functions for the methods of the named type.
func (g *Generator) generate(typeName string) error {
	var functions []Function
	for _, file := range g.pkg.files {
		functions = append(functions, file.methods(typeName, g.exportedOnly)...)
	}

	if len(functions) == 0 {
		return fmt.Errorf("no functions defined for type %s", typeName)
	}

	// Names of the generated functions, and the method each one is for.
	generated := make(map[string]string)

	// Generate code.
	for _, fn := range functions {
		// A method without annotations gets the default error function.
		opts := fn.opts
		if len(opts) == 0 {
			opts = []string{""}
		}

		for i, opt := range opts {
			where := typeName + "." + fn.name
			if len(fn.opts) > 0 {
				where += ": +generr line " + strconv.Itoa(i+1)
			}

			sp, err := parseSpec(opt)
			if err != nil {
				return fmt.Errorf("%s: %w", where, err)
			}

			// Additional functions of a method need distinct names.
			if sp.nameSuffix == "" && i > 0 {
				sp.nameSuffix = strconv.Itoa(i)
			}

			name := "err" + titleCase(fn.name) + sp.nameSuffix
			if other, ok := generated[name]; ok {
				return fmt.Errorf("%s: function %s is already generated for %s.%s; "+
					"rename one with namesuffix, or skip one", where, name, typeName, other)
			}
			generated[name] = fn.name

			if err := g.generateSingle(typeName, name, fn, sp); err != nil {
				return fmt.Errorf("%s: %w", where, err)
			}
		}
	}

	return nil
}

// generateSingle renders the error function name of fn, as described by sp.
func (g *Generator) generateSingle(typeName, name string, fn Function, sp spec) error {
	funcParams := make([]jen.Code, len(sp.params))
	for i, p := range sp.params {
		if err := g.addImports(fn, p.typ); err != nil {
			return err
		}
		funcParams[i] = jen.Id(p.name).Op(p.typ)
	}

	// The operation name is always the first argument of the format.
	callParams := make([]jen.Code, 0, 2+len(sp.args))
	callParams = append(callParams, jen.Lit(sp.format), jen.Lit(fn.String()))
	for _, p := range sp.args {
		callParams = append(callParams, jen.Id(p.name))
	}

	// The receiver of a generic type has to list its type parameters. The
	// generated function does not use them, so they are left blank.
	recv := "*" + typeName
	if fn.typeParams > 0 {
		recv += "[_" + strings.Repeat(", _", fn.typeParams-1) + "]"
	}

	c := jen.Func().
		Params(jen.Op(recv)).
		Id(name).
		Params(funcParams...).
		Parens(jen.Error()).
		Block(
			jen.Return().Qual("fmt", "Errorf").Call(callParams...),
		)

	var buf bytes.Buffer
	if err := c.Render(&buf); err != nil {
		return fmt.Errorf("cannot render %s: %w", name, err)
	}

	g.Printf("// %s is an error function generated for %s.%s\n", name, typeName, fn.name)
	g.Printf("%s\n\n", buf.Bytes())

	return nil
}

// addImports records the imports that the parameter type typ of fn needs in
// the generated file.
func (g *Generator) addImports(fn Function, typ string) error {
	for _, name := range qualifiers(typ) {
		imp, err := g.pkg.resolveImport(fn.file, name)
		if err != nil {
			return fmt.Errorf("parameter type %s: %w", typ, err)
		}

		prev, ok := g.imports[name]
		if !ok {
			g.imports[name] = imp
			continue
		}
		if prev.path != imp.path {
			return fmt.Errorf("parameter type %s: package name %s means %q here, "+
				"but the generated file already uses it for %q", typ, name, imp.path, prev.path)
		}
	}

	return nil
}

// writeImports writes the import declaration of the generated file.
func (g *Generator) writeImports(w *bytes.Buffer) {
	imports := make([]fileImport, 0, len(g.imports))
	for _, imp := range g.imports {
		imports = append(imports, imp)
	}
	slices.SortFunc(imports, func(a, b fileImport) int {
		return cmp.Or(strings.Compare(a.path, b.path), strings.Compare(a.alias, b.alias))
	})

	if len(imports) == 1 {
		fmt.Fprintf(w, "import %s\n", imports[0])
		return
	}

	fmt.Fprintf(w, "import (\n")
	for _, imp := range imports {
		fmt.Fprintf(w, "\t%s\n", imp)
	}
	fmt.Fprintf(w, ")\n")
}

// qualifiers returns the package names that a type expression refers to, such
// as "time" in "[]time.Duration".
func qualifiers(typ string) []string {
	expr, err := parser.ParseExpr(strings.TrimPrefix(typ, "..."))
	if err != nil {
		// Not a type. Rendering the function reports it.
		return nil
	}

	var names []string
	ast.Inspect(expr, func(n ast.Node) bool {
		if sel, ok := n.(*ast.SelectorExpr); ok {
			if id, ok := sel.X.(*ast.Ident); ok && !slices.Contains(names, id.Name) {
				names = append(names, id.Name)
			}
		}
		return true
	})

	return names
}

// resolveImport finds the import that the package name refers to. The file of
// the annotated method decides; the other files of the package are consulted
// when it does not import such a package itself.
func (p *Package) resolveImport(file *File, name string) (fileImport, error) {
	if imp, ok := file.findImport(name); ok {
		return imp, nil
	}

	var found []fileImport
	for _, f := range p.files {
		imp, ok := f.findImport(name)
		if !ok || slices.ContainsFunc(found, func(o fileImport) bool { return o.path == imp.path }) {
			continue
		}
		found = append(found, imp)
	}

	switch len(found) {
	case 0:
		return fileImport{}, fmt.Errorf("no file of package %s imports a package named %s", p.name, name)
	case 1:
		return found[0], nil
	default:
		return fileImport{}, fmt.Errorf("package name %s is ambiguous: other files import both %q and %q; "+
			"import the intended one in the file of the method", name, found[0].path, found[1].path)
	}
}

// findImport returns the import of the file that is referred to by name.
func (f *File) findImport(name string) (fileImport, bool) {
	for _, spec := range f.file.Imports {
		importPath, err := strconv.Unquote(spec.Path.Value)
		if err != nil {
			continue
		}

		imp := fileImport{path: importPath}
		local := path.Base(importPath)
		switch {
		case spec.Name != nil:
			imp.alias = spec.Name.Name
			local = imp.alias
		case f.pkg.info != nil:
			// The name of a package can differ from the last element of its path.
			if pkgName := f.pkg.info.PkgNameOf(spec); pkgName != nil {
				local = pkgName.Name()
			}
		}

		if local == name && local != "_" && local != "." {
			return imp, true
		}
	}

	return fileImport{}, false
}

// formatSource returns the gofmt-ed src.
func formatSource(src []byte) ([]byte, error) {
	out, err := format.Source(src)
	if err != nil {
		// Should never happen, but can arise when developing this code.
		return nil, fmt.Errorf("internal error: invalid Go generated: %w", err)
	}
	return out, nil
}

// Function represents a discovered function.
type Function struct {
	name       string   // The name of the function.
	opts       []string // The provided options for generator.
	str        string   // The unique string representation.
	file       *File    // The file that declares the function.
	typeParams int      // Number of type parameters of the receiver type.
}

func (f *Function) String() string {
	return f.str
}

// methods returns the methods of the named type that are declared in the file
// and that error functions are generated for.
func (f *File) methods(typeName string, exportedOnly bool) []Function {
	var functions []Function

	for _, d := range f.file.Decls {
		decl, ok := d.(*ast.FuncDecl)
		if !ok || decl.Recv == nil || len(decl.Recv.List) == 0 {
			// We only care about method declarations.
			continue
		}

		recv, typeParams := receiverType(decl.Recv.List[0].Type)
		if recv != typeName {
			// This is not the type we're looking for.
			continue
		}

		name := decl.Name.Name

		if isErrorFunc(name) {
			// Do not create for error functions.
			continue
		}

		// skip unexported functions when 'exported' flag is set
		if exportedOnly && !ast.IsExported(name) {
			continue
		}

		fn := Function{
			name:       name,
			opts:       annotations(decl.Doc),
			str:        strings.Join([]string{f.pkg.namespace, name}, "."),
			file:       f,
			typeParams: typeParams,
		}

		// check if function should be skipped
		if len(fn.opts) == 1 && strings.TrimSpace(fn.opts[0]) == optSkip {
			continue
		}

		functions = append(functions, fn)
	}

	return functions
}

// receiverType returns the name of the type of a method receiver, and the
// number of type parameters it lists: "T" and 2 for "*T[K, V]".
func receiverType(expr ast.Expr) (name string, typeParams int) {
	for {
		switch t := expr.(type) {
		case *ast.ParenExpr:
			expr = t.X
		case *ast.StarExpr:
			expr = t.X
		case *ast.IndexExpr:
			typeParams = 1
			expr = t.X
		case *ast.IndexListExpr:
			typeParams = len(t.Indices)
			expr = t.X
		case *ast.Ident:
			return t.Name, typeParams
		default:
			return "", 0
		}
	}
}

// isErrorFunc reports whether name looks like a generated error function:
// "err" followed by anything but a lower-case letter. A method like "errand"
// is not one.
func isErrorFunc(name string) bool {
	rest, ok := strings.CutPrefix(name, "err")
	if !ok {
		return false
	}
	next, _ := utf8.DecodeRuneInString(rest)
	return !unicode.IsLower(next)
}

// annotations returns the options of each "+generr" line of a doc comment.
// The marker has to start the line, and is separated from its options by a
// colon or a space: "// +generr:format=...".
func annotations(doc *ast.CommentGroup) []string {
	if doc == nil {
		return nil
	}

	var opts []string
	for _, comment := range doc.List {
		text, ok := strings.CutPrefix(comment.Text, "//")
		if !ok {
			continue
		}
		rest, ok := strings.CutPrefix(strings.TrimSpace(text), "+generr")
		if !ok {
			continue
		}

		switch {
		case rest == "":
			opts = append(opts, "")
		case strings.ContainsRune(": \t", rune(rest[0])):
			opts = append(opts, rest[1:])
		}
	}

	return opts
}

// Helpers

func titleCase(s string) string {
	r := []rune(s)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}
